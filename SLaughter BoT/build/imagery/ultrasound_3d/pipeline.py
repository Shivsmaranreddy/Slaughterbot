"""Synthetic or calibrated aligned-volume autoencoder. No freehand reconstruction claim."""
from pathlib import Path
import copy, json
import numpy as np
import torch
from torch import nn
from build.integration.common import ROOT, seed_all, finalize, write_json, sha256
from build.imagery.cnn.data import validate_manifest

class Autoencoder(nn.Module):
    def __init__(self):
        super().__init__()
        self.net=nn.Sequential(nn.Conv3d(1,8,3,2,1),nn.ReLU(),nn.Conv3d(8,16,3,2,1),nn.ReLU(),
            nn.ConvTranspose3d(16,8,4,2,1),nn.ReLU(),nn.ConvTranspose3d(8,1,4,2,1),nn.Sigmoid())
    def forward(self,x): return self.net(x)

def load_volume(path):
    with np.load(path,allow_pickle=False) as a:
        volume=np.asarray(a['volume'],dtype=np.float32)
        spacing=np.asarray(a['spacing_mm'],dtype=np.float32)
        orientation=np.asarray(a['orientation'],dtype=np.float32)
    if volume.shape!=(32,32,32) or not np.isfinite(volume).all() or volume.min()<0 or volume.max()>1:
        raise ValueError('Expected finite normalized 32x32x32 volume')
    if spacing.shape!=(3,) or not np.isfinite(spacing).all() or (spacing<=0).any():
        raise ValueError('Invalid physical spacing')
    if orientation.shape!=(3,3) or not np.isfinite(orientation).all() or not np.allclose(orientation.T@orientation,np.eye(3),atol=1e-4) or np.linalg.det(orientation)<0.99:
        raise ValueError('Invalid orientation matrix')
    return volume,spacing,orientation

def synthetic_dataset(folder, count=60, seed=42):
    folder=Path(folder); folder.mkdir(parents=True,exist_ok=True)
    rng=np.random.default_rng(seed); grid=np.indices((32,32,32)); samples=[]
    for i in range(count):
        center=rng.uniform(10,22,3)[:,None,None,None]; radii=rng.uniform(4,9,3)[:,None,None,None]
        phantom=(((grid-center)/radii)**2).sum(0)<1
        volume=np.clip(phantom.astype(np.float32)*rng.uniform(0.5,0.9)+rng.normal(0,0.08,(32,32,32)),0,1).astype(np.float32)
        f=folder/f'phantom_{i:04d}.npz'; np.savez_compressed(f,volume=volume,spacing_mm=np.ones(3),orientation=np.eye(3))
        samples.append({'path':f.name,'sha256':sha256(f),'group_id':f'phantom_{i}',
                        'split':'train' if i<int(count*.7) else 'val' if i<int(count*.85) else 'test','provenance':'synthetic'})
    m={'name':'Synthetic ellipsoid phantoms','source':'Repository synthetic_dataset function','license':'CC0-1.0',
       'citation':'Generated by this project; seed recorded','modality':'volume','provenance':'synthetic',
       'collection_method':f'Independent random ellipsoids; seed {seed}','limitations':'Not ultrasound physics or anatomy',
       'permission_confirmed':True,'samples':samples}
    write_json(folder/'manifest.json',m); return folder/'manifest.json'

def train(manifest_path,data_root,epochs=10,seed=42,resume=None):
    seed_all(seed); m=validate_manifest(manifest_path,data_root,'volume')
    device='cuda' if torch.cuda.is_available() else 'cpu'; model=Autoencoder().to(device)
    opt=torch.optim.Adam(model.parameters(),lr=0.001)
    sets={s:[r for r in m['samples'] if r['split']==s] for s in ['train','val','test']}
    best_loss=float('inf'); best=None; history=[]; start=0; fingerprint=sha256(manifest_path)
    if resume:
        c=torch.load(resume,map_location=device,weights_only=True)
        if c['dataset_sha256']!=fingerprint: raise ValueError('Resume data mismatch')
        model.load_state_dict(c['model']); opt.load_state_dict(c['optimizer'])
        start=c['epoch']+1; best_loss=c['best_loss']; best=c['best']; history=c['history']
    for epoch in range(start,epochs):
        row={'epoch':epoch}
        for split in ['train','val']:
            model.train(split=='train'); losses=[]
            for record in sets[split]:
                v,_,_=load_volume(Path(data_root)/record['path']); x=torch.from_numpy(v)[None,None].to(device)
                with torch.set_grad_enabled(split=='train'):
                    loss=nn.functional.mse_loss(model(x),x)
                    if split=='train': opt.zero_grad(); loss.backward(); opt.step()
                losses.append(loss.item())
            row[split]=float(np.mean(losses))
        history.append(row)
        if row['val']<best_loss: best_loss=row['val']; best=copy.deepcopy(model.state_dict())
        checkpoint=ROOT/'output/checkpoints/ultrasound_last.pt'; checkpoint.parent.mkdir(parents=True,exist_ok=True)
        torch.save({'epoch':epoch,'model':model.state_dict(),'optimizer':opt.state_dict(),'best':best,
                    'best_loss':best_loss,'history':history,'dataset_sha256':fingerprint},checkpoint)
    if best is None: raise ValueError('No training epoch completed')
    model.load_state_dict(best); model.eval(); errors=[]; baseline=[]
    with torch.no_grad():
        for record in sets['test']:
            v,_,_=load_volume(Path(data_root)/record['path']); x=torch.from_numpy(v)[None,None].to(device)
            errors.append(float(nn.functional.mse_loss(model(x),x))); baseline.append(float(np.mean((v-v.mean())**2)))
    folder=ROOT/'output/models/model_2_ultrasound_3d'; folder.mkdir(parents=True,exist_ok=True)
    artifact=folder/'weights.pt'; torch.save({k:v.cpu() for k,v in best.items()},artifact)
    report={'test_mse':float(np.mean(errors)),'constant_mean_baseline_mse':float(np.mean(baseline)),
            'test_volumes':len(errors),'scope':m['provenance'],'anatomical_validation':False}
    finalize(folder,'model_2_ultrasound_3d',artifact,{'epochs':epochs,'seed':seed,'history':history,'dataset_sha256':fingerprint},report,{'shape':[32,32,32],'normalization':'input must already be [0,1]'},m['provenance'])
    return report

def predict(folder,volume_path):
    v,spacing,orientation=load_volume(volume_path); model=Autoencoder()
    model.load_state_dict(torch.load(Path(folder)/'weights.pt',map_location='cpu',weights_only=True)); model.eval()
    with torch.no_grad(): reconstructed=model(torch.from_numpy(v)[None,None])[0,0].numpy()
    return {'status':'EXPERIMENTAL','mse':float(np.mean((v-reconstructed)**2)),
            'spacing_mm':spacing.tolist(),'orientation':orientation.tolist(),'shape':list(v.shape),'anatomical_validation':False}

def visualize(folder,volume_path,destination):
    v,spacing,_=load_volume(volume_path); model=Autoencoder()
    model.load_state_dict(torch.load(Path(folder)/'weights.pt',map_location='cpu',weights_only=True)); model.eval()
    with torch.no_grad(): r=model(torch.from_numpy(v)[None,None])[0,0].numpy()
    import matplotlib.pyplot as plt
    fig=plt.figure(figsize=(12,4)); a=fig.add_subplot(131); a.imshow(v[16],cmap='gray'); a.set_title('Input slice')
    a=fig.add_subplot(132); a.imshow(r[16],cmap='gray'); a.set_title('Reconstructed slice')
    a=fig.add_subplot(133,projection='3d'); points=np.argwhere(r>0.5)[::4]
    if len(points): a.scatter(*(points*spacing).T,s=1)
    a.set_title('Thresholded voxels (mm)'); fig.savefig(destination); plt.close(fig)
    np.savez_compressed(Path(destination).with_suffix('.npz'),volume=r,spacing_mm=spacing,orientation=load_volume(volume_path)[2])
